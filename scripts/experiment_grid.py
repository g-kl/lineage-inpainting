"""Generate + submit the mouse-embryo model grid's generator-owned configs.

The grid (analysis/figures/grid_summary/concept.md) is unshared pool / split,
sampling model x pairing x imputing model, the full (ca + path) aligner, no
extender, seed 42, 20k steps:

    bridges cfm / vpsde  x  id / id_sg / nn / nn_sg / idnn_leaf
    = 10 generated configs

The one-step (fullen) family, the plain Tree Tx pool (nondelta) and the aligner
ablation are hand-made configs beside these in
config/experiment/grid/bridge/ (scripts/grid_eval/README.md); `gen` overwrites
only the names it emits. The split loss covers the full tree for every pairing
(objective default). Every grid config is committed.

    python scripts/experiment_grid.py gen                    # emit YAMLs + manifest.csv
    python scripts/experiment_grid.py submit --seed 42 [--dry] [--filter pairing=idnn_leaf]
"""
from __future__ import annotations

import argparse
import csv
import itertools
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRID_DIR = ROOT / "config" / "experiment" / "grid"
MANIFEST = GRID_DIR / "grid_manifest.csv"
SBATCH = ROOT / "scripts" / "aligner_sweep.sbatch"

YAML_HEADER = "# @package _global_\n#\n# AUTO-GENERATED by scripts/experiment_grid.py -- do not edit by hand.\n"


BRIDGE_DISTNL_PREFIX = {
    "std": "bridge_delta_tree_flow",
}
TF_DISTNL_PREFIX = {
    "full": "full_energy_delta_tree_former",
}
ALIGNER_GROUP = {
    # the pair-ordered CommonAncestor variant (marginal + path + CA features).
    "ca": "slice_marginal_ca_path",
}
# The pooler next to the splitter: the DeltaTreeFormer.
POOL_GROUP_UNSHARED = {
    "dtfm": "delta_tree_former",
}
# Extender choice. `graft` = ConditionalGraftExtender;
# `none` = NullExtender (no leaf extension).
EXTENDER_GROUP = {
    "graft": "conditional_graft",
    "none": "none",
}
# Pairing -> Hydra group. `nn` maps to nearest_neighbor.yaml
# (clonal_reference=false) and `nnclo` to the clonal-restricted variant
# (nearest_neighbor_clonal.yaml; clonal_reference=true). The `_sg` siblings
# set stop_grad=true so the splitter loss never reaches the pooler -- the
# pooler is then trained only by the aligner head running on its outputs.
PAIRING_GROUP = {
    "id": "identity",
    "nn": "nearest_neighbor",
    "nnclo": "nearest_neighbor_clonal",
    "id_sg": "identity_sg",
    "nn_sg": "nearest_neighbor_sg",
    "nnclo_sg": "nearest_neighbor_clonal_sg",
    # Alternating: trainer cycles [Identity, NN]; combines the regulative
    # identity signal with the NN snap.
    "idnn": "id_nn_alt",
    # Same alternating pairing, but the objective also rotates per-step:
    # under IdentityPairing the splitter is supervised on leaves only (the
    # regulative reconstruction signal), under NearestNeighborPairing it
    # supervises everything-except-anchor (full-tree fill).
    "idnn_leaf": "id_nn_alt",
}


def bridge_pool_split(shared: bool, bridge: str, distnl: str,
                      pool_kind: str = "dtfm") -> tuple[str, str]:
    """Resolve (pooler, splitter) Hydra groups for the bridge family."""
    base = BRIDGE_DISTNL_PREFIX[distnl]
    if bridge == "vpsde":
        base = base + "_vpsde"
    split = base
    pool = base if shared else POOL_GROUP_UNSHARED[pool_kind]
    return pool, split


def tf_pool_split(shared: bool, distnl: str,
                  pool_kind: str = "dtfm") -> tuple[str, str]:
    """Resolve (pooler, splitter) groups for the TreeFormer (energy) family."""
    split = TF_DISTNL_PREFIX[distnl]
    pool = split if shared else POOL_GROUP_UNSHARED[pool_kind]
    return pool, split


def emit_yaml(path: Path, *, name: str, pool: str, split: str, pairing: str,
              shared: bool, sa: bool, distnl: str, aligner: str, extender: str,
              descr: str) -> None:
    pairing_group = PAIRING_GROUP[pairing]
    aligner_group = ALIGNER_GROUP[aligner]
    extender_group = EXTENDER_GROUP[extender]
    saw = 1 if sa else 0
    body = YAML_HEADER + f"# Combo: {descr}\n"
    body += "defaults:\n"
    body += "  - override /dataset: mouse_embryo\n"
    body += f"  - override /pooler: {pool}\n"
    body += f"  - override /splitter: {split}\n"
    body += f"  - override /aligner: {aligner_group}\n"
    body += f"  - override /pairing: {pairing_group}\n"
    body += f"  - override /extender: {extender_group}\n"
    body += "  - override /record_sampler: paired_offset_sample_offset\n"
    body += "  - override /training: default\n\n"
    body += f"experiment_name: mouse_embryo_grid_{name}\n"
    body += f"share_pool_split: {'true' if shared else 'false'}\n\n"
    body += "objective:\n"
    body += f"  split_align_weight: {saw}\n"
    # the split loss covers the full tree for every pairing (the objective
    # default, leaf_reconstruction_only: false); no per-pairing override.
    body += "\n"
    # `full` distributional variants route per-sample noise through the entire
    # transformer (M independent encodes); K=8 doesn't fit, so override to K=2.
    if distnl == "full":
        body += "pooler:\n"
        body += "  n_energy_samples: 2\n"
        body += "splitter:\n"
        body += "  n_energy_samples: 2\n\n"
    body += "optimizer:\n"
    body += "  lr: 1e-3\n"
    body += "  warmup_steps: 500\n"
    body += "  weight_decay: 0.01\n"
    body += "  adam_eps: 1e-6\n\n"
    # Memory budgets, all measured on 80GB H100:
    #  - SA configs blow 80GB at 1024 (stage-2 geomloss energy distance), so
    #    they drop to 768 for ~25% headroom.
    #  - `full` distnl configs route M independent samples through the entire
    #    transformer rather than a cheap output-head latent, which also blows
    #    1024; they run at K=2 with 768 trees.
    n_trees_val = 768 if (sa or distnl == "full") else 1024
    body += "training:\n"
    body += "  n_steps: 20000\n"
    body += "  log_every: 100\n"
    body += "  save_every: 5000\n"
    body += f"  n_trees: {n_trees_val}\n"
    body += "  n_records: 2\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)


def gen() -> None:
    bridge_dir = GRID_DIR / "bridge"
    bridge_dir.mkdir(parents=True, exist_ok=True)   # emitted names are overwritten; hand-made configs stay

    rows = []

    # the grid's axes: unshared pool / split, the two bridges, the five pairings, the
    # full (ca + path) aligner, the Delta Tree Tx pool, no extender. the one-step
    # (fullen) family, the plain Tree Tx pool and the aligner ablation are hand-made
    # configs beside these (see scripts/grid_eval/README.md).
    for bridge, pairing in itertools.product(
        ["cfm", "vpsde"], ["id", "id_sg", "nn", "nn_sg", "idnn_leaf"],
    ):
        shared, sa, distnl, aligner, extender = False, False, "std", "ca", "none"
        pool_kind = "dtfm"
        pool, split = bridge_pool_split(shared, bridge, distnl, pool_kind)
        name = f"bridge_unshared_{bridge}_{pairing}_nosa_std_none"
        descr = (f"family=bridge shared={shared} bridge={bridge} pair={pairing} "
                 f"sa={sa} distnl={distnl} aligner={aligner} pool={pool_kind} "
                 f"extender={extender}")
        emit_yaml(bridge_dir / f"{name}.yaml", name=name, pool=pool, split=split,
                  pairing=pairing, shared=shared, sa=sa, distnl=distnl,
                  aligner=aligner, extender=extender, descr=descr)
        rows.append({
            "family": "bridge", "name": name, "shared": shared, "bridge": bridge,
            "pairing": pairing, "sa": sa, "distnl": distnl, "aligner": aligner,
            "pool": pool_kind, "extender": extender,
            "pool_group": pool, "split": split, "config": f"grid/bridge/{name}",
        })

    with MANIFEST.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    print(f"wrote {len(rows)} bridge configs -> {GRID_DIR}")
    print(f"manifest: {MANIFEST.relative_to(ROOT)}")


def submit(family: str, seed: int, dry: bool, filter_str: str | None = None) -> None:
    if not MANIFEST.exists():
        sys.exit(f"manifest not found: {MANIFEST} (run `gen` first)")
    if not SBATCH.exists():
        sys.exit(f"sbatch wrapper not found: {SBATCH}")
    with MANIFEST.open() as f:
        rows = list(csv.DictReader(f))
    if family != "both":
        rows = [r for r in rows if r["family"] == family]
    if filter_str:
        # "shared=True,sa=False,distnl=full" -> require all kv pairs match
        # (string match against manifest values, which are all strings)
        constraints = dict(kv.split("=", 1) for kv in filter_str.split(","))
        rows = [r for r in rows if all(r.get(k) == v for k, v in constraints.items())]
    print(f"submitting {len(rows)} jobs (family={family}, seed={seed}"
          + (f", filter={filter_str}" if filter_str else "") + ")")
    for r in rows:
        # The sbatch wrapper always adds `pairing=${PAIRING}` to the Hydra
        # overrides (default 'identity'), which clobbers the experiment
        # yaml's `defaults: - override /pairing: ...`. Pass the full
        # PAIRING_GROUP entry so axis values like nnclo / id_sg / idnn /
        # idnn_leaf actually use their intended pairing config.
        pairing_group = PAIRING_GROUP[r["pairing"]]
        cmd = [
            "sbatch", "--parsable",
            "--job-name", r["name"],
            # kempner_h100: 80GB H100, non-preemptible. 40GB cards OOM at
            # n_trees=1024. --requeue retries node failures and timeouts.
            "--partition=kempner_h100",
            "--requeue",
            f"--export=ALL,EXPERIMENT={r['config']},PAIRING={pairing_group},SEED={seed}",
            str(SBATCH),
            f"seed={seed}",
        ]
        if dry:
            print("DRY:", " ".join(cmd))
            continue
        jid = subprocess.check_output(cmd, text=True).strip()
        print(f"SUBMITTED {r['name']}: {jid}")


def main() -> None:
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("gen")
    s = sub.add_parser("submit")
    s.add_argument("--family", choices=["bridge"], default="bridge")
    s.add_argument("--seed", type=int, required=True)
    s.add_argument("--dry", action="store_true")
    s.add_argument("--filter", default=None,
                   help='Filter manifest rows by "key=value,key=value" (e.g. '
                        '"shared=True,sa=False,distnl=full")')
    a = p.parse_args()
    if a.cmd == "gen":
        gen()
    elif a.cmd == "submit":
        submit(a.family, a.seed, a.dry, a.filter)


if __name__ == "__main__":
    main()
