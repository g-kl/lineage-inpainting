def umap_window(L):
    """a sheet's zoom window: the box its link endpoints fill between the D_QUANT
    percentiles, padded, then widened if it is narrower than D_ASPECT_MIN. returns
    (xlim, ylim, width per height)."""
    q = (D_QUANT, 100 - D_QUANT)
    lim = []
    for a, b in (("src_u1", "leaf_u1"), ("src_u2", "leaf_u2")):
        lo, hi = np.nanpercentile(np.r_[L[a].values, L[b].values], q)
        pad = D_PAD * (hi - lo)
        lim.append(np.array([lo - pad, hi + pad]))
    x, y = lim
    h = y[1] - y[0]
    w = max(x[1] - x[0], D_ASPECT_MIN * h)
    c = x.mean()
    return (c - w / 2, c + w / 2), tuple(y), w / h


def trim(t):
    for a, b in TRIM:
        t = t.replace(a, b)
    return t


def figure(w, h):
    """a figure of exactly (w, h) inches plus a `box` that places axes in inches."""
    import matplotlib.pyplot as plt
    apply_rc()
    fig = plt.figure(figsize=(w, h))
    return fig, lambda x, y, bw, bh: fig.add_axes([x / w, y / h, bw / w, bh / h])


def save(fig, name):
    """write a panel svg into imgs/panels/."""
    import matplotlib.pyplot as plt
    p = os.path.join(PANELS, f"{name}.svg")
    fig.savefig(p)
    plt.close(fig)
    print(f"wrote {os.path.relpath(p, base_dir)}", flush=True)
    return p
