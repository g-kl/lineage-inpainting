def _score_cmap(base=P.DIVERGING_CMAP, n=256):
    """the shared diverging map with its neutral middle darkened to LUM_MAX. panel e
    draws the score as lines, and the raw map's centre is near-white."""
    from matplotlib.colors import ListedColormap
    C = np.array(base(np.linspace(0, 1, n)))
    lum = C[:, :3] @ (0.2126, 0.7152, 0.0722)
    C[:, :3] *= np.minimum(1.0, LUM_MAX / lum)[:, None]
    return ListedColormap(C, name="score")


