def meso_neg(ty):
    """endothelium against the rest of mesoderm, the other endothelial types held out
    of the negative set so the axis is not diluted by near-identical cells."""
    return ~np.isin(ty, ENDO)


def neuron_neg(ty):
    """a neuron type against the other neuron types only. against all of neural
    ectoderm -- which at E9.5 is mostly progenitors -- the axis comes out
    pan-neuronal, and one type's program then lights up another type's cells."""
    return np.array(["neuron" in t for t in ty])


def ec_x(t, lin):
    """paraxial or lateral plate, but only for cells that are not already
    endothelium -- endocardial cell is annotated lateral plate."""
    if t in ENDO:
        return ""
    return {"paraxial mesoderm": "paraxial",
            "lateral plate mesoderm": "lateral plate"}.get(lin, "")


def ap_x(target):
    """the target type is never its own source, so a type that names a region cannot
    smuggle its identity into the positional axis."""
    def f(t, lin):
        if t == target:
            return ""
        if t.startswith("hindbrain"):
            return "anterior"
        if t.startswith("spinal cord"):
            return "posterior"
        return ""
    return f


FOREBRAIN = ("forebrain", "telencephalon", "diencephalon", "hypothalamus", "eye field")


def tube_x(t, lin):
    """a neural source's region along the neural tube. neuron types are not regions
    ("midbrain neuron" starts with "midbrain"), and floor plate, roof plate and neural
    crest are not positional."""
    if "neuron" in t:
        return ""
    if t in FOREBRAIN:
        return "forebrain"
    for r in ("midbrain", "hindbrain", "spinal cord"):
        if t.startswith(r):
            return r
    return ""


